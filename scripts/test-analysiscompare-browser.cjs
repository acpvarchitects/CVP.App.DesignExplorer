const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
let browser;
(async () => {
    browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader', '--no-proxy-server'] });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = process.env.ANALYSIS_PREVIEW_URL || 'http://127.0.0.1:8127';
    const project = 'ZRCH_261113_HotelNoise_Option01_Grid1p6_110428:Option 1,ZRCH_261113_HotelNoise_Option02_Grid1p6_111312:Option 2';
    await page.goto(`${base}/v2/analysis.html?${new URLSearchParams({ PROJECT: project, an: 'an_road_noise_volume', mode: '3d', sc: 'exposure' })}`);
    const frames = () => page.frames().filter(f => f.parentFrame() === page.mainFrame());
    await page.waitForFunction(() => ['view1', 'view2'].every(k => new URLSearchParams(location.search).has(k)), { }, { timeout: 180000 });
    assert.equal(frames().length, 2);
    await page.locator('.ac-tabs button').filter({ hasText: /^Compare$/ }).click();
    await page.waitForFunction(() => document.querySelector('#acStatus').textContent.includes('Same colour'));
    assert.equal(await page.locator('.ac-option:visible').count(), 2);
    const [left, right] = frames();
    await page.screenshot({ path: path.resolve('v2/_test/noise-comparison-3d.png') });
    await left.locator('#zoomIn').click();
    await page.waitForFunction(() => {
        const p = new URLSearchParams(location.search);
        return JSON.parse(p.get('view1')).camera.join() === JSON.parse(p.get('view2')).camera.join();
    });
    await left.locator('#volDots').check();
    await right.waitForFunction(() => document.querySelector('#volDots').checked);
    await left.locator('#volDots').uncheck();
    await left.locator('[data-mode="plan"]').click();
    await right.waitForFunction(() => document.querySelector('#view').dataset.mode === 'plan');
    await left.locator('#volElev').fill('18');
    await left.locator('#volElev').dispatchEvent('change');
    await right.waitForFunction(() => +document.querySelector('#volElev').value === 18);
    await page.locator('#acScenario').selectOption('vegetationDelta');
    for (const frame of frames()) await frame.waitForFunction(() => new URLSearchParams(location.search).get('sc') === 'vegetationDelta');
    await page.waitForFunction(() => document.querySelector('#acLegend').textContent.includes('3 dB'));
    await page.locator('#acLink').uncheck();
    await left.locator('[data-mode="section"]').click();
    assert.equal(await right.locator('#view').getAttribute('data-mode'), 'plan');
    await page.locator('#acLink').check();
    await right.waitForFunction(() => document.querySelector('#view').dataset.mode === 'section');
    await left.locator('[data-vx="4"]').click();
    await right.waitForFunction(() => document.querySelector('[data-vx="4"]').classList.contains('on'));
    await page.locator('#acDetails').check();
    await left.locator('.an-side').waitFor({ state: 'visible' });
    await page.locator('#acDetails').uncheck();
    await left.locator('.an-side').waitFor({ state: 'hidden' });
    await page.locator('.ac-option').first().getByRole('button', { name: 'Expand Option 1' }).click();
    assert.equal(await page.locator('.ac-option:visible').count(), 1);
    await left.locator('.an-side').waitFor({ state: 'visible' });
    await page.locator('.ac-tabs button').filter({ hasText: /^Option 2$/ }).click();
    assert.equal(await right.locator('#view').getAttribute('data-mode'), 'section');
    await page.locator('.ac-tabs button').filter({ hasText: /^Compare$/ }).click();
    const sharedUrl = page.url();
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#acStatus')?.textContent.includes('Same colour'), {}, { timeout: 180000 });
    assert.equal(new URL(sharedUrl).searchParams.get('tab'), 'compare');
    for (const frame of frames()) assert.equal(await frame.locator('#view').getAttribute('data-mode'), 'section');
    await page.screenshot({ path: path.resolve('v2/_test/noise-comparison-desktop.png') });
    await page.setViewportSize({ width: 700, height: 900 });
    assert.ok((await page.locator('.ac-tabs').boundingBox()).height >= 30, 'tabs remain visible on narrow screens');
    await page.screenshot({ path: path.resolve('v2/_test/noise-comparison-mobile.png') });
    assert.ok(await page.locator('.ac-option').first().evaluate(el => el.getBoundingClientRect().width < 700));
    // Original single-study links still open the full analysis directly.
    await page.goto(`${base}/v2/analysis.html?PROJECT=${project.split(',')[0]}&an=an_road_noise_volume&mode=3d`);
    await page.waitForFunction(() => document.querySelector('#scoreValue').textContent.includes('dB'), {}, { timeout: 180000 });
    assert.equal(await page.locator('iframe').count(), 0);
    assert.equal(await page.locator('.an-side').isVisible(), true);
    assert.deepEqual(errors, []);
    console.log('PASS real studies: full tabs, linked plan/section/elevation, scenario scales, unlink/relink, expand, URL restore, responsive layout, single-study regression');
    await browser.close();
})().catch(async e => { console.error(e); await browser?.close(); process.exitCode = 1; });
