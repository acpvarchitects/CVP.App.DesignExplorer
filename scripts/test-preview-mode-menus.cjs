const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const path=require('node:path'),os=require('node:os');
let browser;
(async()=>{
    browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader']});
    const page=await browser.newPage({viewport:{width:1366,height:768},reducedMotion:'reduce'});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(process.env.DE_TEST_URL||'http://127.0.0.1:8124/v2/?PROJECT=ZRCH_B4_F_20261112,ZRCH_B23_F_20261112,ZRCH_STEP12_B4_20261112,ZRCH_STEP12_B19_20261112&option=1&mode=image');
    const button=key=>page.locator(`#modeButtons [data-mode="${key}"]`);
    const menu=page.locator('#previewModeMenu');
    await button('analysis').waitFor();
    await button('analysis').click();
    assert.equal(await menu.evaluate(el=>el.matches(':popover-open')),true);
    assert.equal(new URL(page.url()).searchParams.get('mode'),'image','opening a category does not switch the view');
    const analysisLabels=await menu.locator('button').allTextContents();
    assert.ok(analysisLabels.length>=2);
    await page.screenshot({path:path.join(os.tmpdir(),'preview-analysis-menu.png')});
    const name=analysisLabels[1].replace('✓','').trim();
    await menu.locator('button').nth(1).click();
    assert.ok((await button('analysis').textContent()).includes(name));
    assert.equal(await page.locator('#layerSelect').isVisible(),false);
    assert.equal(new URL(page.url()).searchParams.get('mode'),'analysis');
    await button('model').click();
    assert.equal((await button('analysis').textContent()).replace(/\s+/g,' ').trim(),'3D analysis ▾');
    await button('analysis').focus();await page.keyboard.press('ArrowDown');
    assert.equal(await menu.evaluate(el=>el.matches(':popover-open')),true);
    await page.keyboard.press('End');
    assert.equal(await menu.locator('button').last().evaluate(el=>document.activeElement===el),true);
    await page.keyboard.press('Escape');
    assert.equal(await button('analysis').evaluate(el=>document.activeElement===el),true);
    assert.equal(new URL(page.url()).searchParams.get('mode'),'model');
    await button('table').click();
    const tableName=(await menu.locator('button').first().textContent()).replace('✓','').trim();
    await menu.locator('button').first().click();
    assert.ok((await button('table').textContent()).includes(tableName));
    assert.equal(await page.locator('#layerSelect').isVisible(),false);
    await button('model').click();
    assert.equal((await button('table').textContent()).replace(/\s+/g,' ').trim(),'Table ▾');
    await button('analysis').click();
    await page.locator('#previewTitle').click();
    assert.equal(await menu.evaluate(el=>el.matches(':popover-open')),false);
    await button('analysis').click();await page.keyboard.press('Tab');
    assert.equal(await menu.evaluate(el=>el.matches(':popover-open')),false);
    for(const width of [1366,850,390]){
        await page.setViewportSize({width,height:768});
        await page.waitForTimeout(450);
        await button('analysis').click();
        await menu.waitFor({state:'visible'});
        const b=await menu.boundingBox();
        assert.ok(b.x>=0&&b.x+b.width<=width+1&&b.y>=0&&b.y+b.height<=769,JSON.stringify(b));
        await page.keyboard.press('Escape');
    }
    assert.deepEqual(errors,[]);
    console.log('PASS integrated menus: real analysis/table choices, neutral inactive labels, outside click, keyboard and responsive bounds');
    await browser.close();
})().catch(async error=>{console.error(error);await browser?.close();process.exitCode=1;});
